# ==============================================================================
# Fetch vendored browser assets into web/vendor
#
# The UI must load with no third party origins so that a strict
# Content-Security-Policy of default-src 'self' can be enforced, and so the
# lecturer demo does not depend on a CDN staying reachable.
#
# Run once after cloning, and again only when bumping a pinned version.
# ==============================================================================

[CmdletBinding()]
param(
    [string]$TailwindVersion = "4.3.5",
    [string]$AlpineVersion = "3.17.5",
    [switch]$Force
)

$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

$root = Split-Path -Parent $PSScriptRoot
if (-not (Test-Path (Join-Path $root "go.mod"))) {
    $root = (Get-Location).Path
}
$vendorDir = Join-Path $root "web\vendor"
New-Item -ItemType Directory -Force -Path $vendorDir | Out-Null

$assets = @(
    @{
        Name = "tailwind-browser.min.js"
        Url  = "https://cdn.jsdelivr.net/npm/@tailwindcss/browser@$TailwindVersion/dist/index.global.min.js"
        Note = "Tailwind CSS v$TailwindVersion browser runtime (@tailwindcss/browser)"
    },
    @{
        Name = "alpine.min.js"
        Url  = "https://cdnjs.cloudflare.com/ajax/libs/alpinejs/$AlpineVersion/cdn.min.js"
        Note = "Alpine.js v$AlpineVersion CDN build"
    }
)

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("# Vendored browser assets")
$lines.Add("# Generated by deploy/fetch-assets.ps1. Do not edit by hand.")
$lines.Add("")

foreach ($asset in $assets) {
    $dest = Join-Path $vendorDir $asset.Name
    if ((Test-Path $dest) -and (-not $Force)) {
        Write-Host "[assets] keep existing $($asset.Name)"
    }
    else {
        Write-Host "[assets] downloading $($asset.Url)"
        Invoke-WebRequest -Uri $asset.Url -OutFile $dest -UseBasicParsing
    }

    $hash = (Get-FileHash -Algorithm SHA256 -Path $dest).Hash.ToLowerInvariant()
    $size = (Get-Item $dest).Length
    $lines.Add("sha256  $hash  $($asset.Name)  $size  $($asset.Note)")
    Write-Host "[assets] $($asset.Name) sha256=$hash size=$size"
}

$lines.Add("")
Set-Content -Path (Join-Path $vendorDir "CHECKSUMS.txt") -Value $lines -Encoding ascii
Write-Host "[assets] wrote $vendorDir\CHECKSUMS.txt"
Write-Host "[assets] done. go:embed will pick these up on the next build."