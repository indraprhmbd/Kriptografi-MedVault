#!/usr/bin/env bash
# ==============================================================================
# Fetch vendored browser assets into web/vendor
#
# The UI must load with no third party origins so that a strict
# Content-Security-Policy of default-src 'self' can be enforced, and so the
# lecturer demo does not depend on a CDN staying reachable.
#
# Run once after cloning, and again only when bumping a pinned version.
# ==============================================================================

set -euo pipefail

TAILWIND_VERSION="${TAILWIND_VERSION:-4.3.5}"
ALPINE_VERSION="${ALPINE_VERSION:-3.17.5}"
FORCE="${FORCE:-0}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
VENDOR_DIR="${ROOT_DIR}/web/vendor"

mkdir -p "${VENDOR_DIR}"

fetch() {
    local name="$1"
    local url="$2"
    local note="$3"
    local dest="${VENDOR_DIR}/${name}"

    if [[ -f "${dest}" && "${FORCE}" != "1" ]]; then
        echo "[assets] keep existing ${name}"
    else
        echo "[assets] downloading ${url}"
        if command -v curl >/dev/null 2>&1; then
            curl -fsSL "${url}" -o "${dest}"
        else
            wget -qO "${dest}" "${url}"
        fi
    fi

    local hash size
    hash="$(sha256sum "${dest}" | awk '{print $1}')"
    size="$(stat -c%s "${dest}")"
    echo "[assets] ${name} sha256=${hash} size=${size}"
    printf 'sha256  %s  %s  %s  %s\n' "${hash}" "${name}" "${size}" "${note}"
}

{
    echo "# Vendored browser assets"
    echo "# Generated by deploy/fetch-assets.sh. Do not edit by hand."
    echo ""
    fetch "tailwind-browser.min.js" \
        "https://cdn.jsdelivr.net/npm/@tailwindcss/browser@${TAILWIND_VERSION}/dist/index.global.min.js" \
        "Tailwind CSS v${TAILWIND_VERSION} browser runtime (@tailwindcss/browser)"
    fetch "alpine.min.js" \
        "https://cdnjs.cloudflare.com/ajax/libs/alpinejs/${ALPINE_VERSION}/cdn.min.js" \
        "Alpine.js v${ALPINE_VERSION} CDN build"
    echo ""
} > "${VENDOR_DIR}/CHECKSUMS.txt"

echo "[assets] wrote ${VENDOR_DIR}/CHECKSUMS.txt"
echo "[assets] done. go:embed will pick these up on the next build."