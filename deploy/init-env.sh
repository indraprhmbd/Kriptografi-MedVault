#!/usr/bin/env bash
# Generate /home/medvault/.env with fresh key material.
#
# Runs as the medvault user, so no sudo is required. Usage:
#   bash deploy/init-env.sh <rpid> <origin>
# Example:
#   bash deploy/init-env.sh medvault.example.com https://medvault.example.com
set -euo pipefail

BASE="${MEDVAULT_BASE:-/home/medvault}"
ENV_FILE="$BASE/.env"
RPID="${1:-localhost}"
ORIGIN="${2:-http://localhost:8095}"

if [[ -s "$ENV_FILE" && "${FORCE:-0}" != "1" ]]; then
  echo "$ENV_FILE already exists and is not empty. Set FORCE=1 to overwrite." >&2
  exit 1
fi

if [[ ! -x "$BASE/bin/medvault-validator-keygen" ]]; then
  echo "$BASE/bin/medvault-validator-keygen is missing, run deploy.ps1 first" >&2
  exit 1
fi

read -r VALIDATOR_PRIV VALIDATOR_PUB < <("$BASE/bin/medvault-validator-keygen" -short)

mkdir -p "$BASE/storage/encrypted_labs" "$BASE/storage/stego_scans" "$BASE/storage/biometrics"

umask 077
cat > "$ENV_FILE" <<EOF
# Generated by deploy/init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
MEDVAULT_APP_ADDR=0.0.0.0:8095
MEDVAULT_VALIDATOR_ADDR=0.0.0.0:8096
MEDVAULT_VALIDATOR_URL=http://127.0.0.1:8096

MEDVAULT_DB_PATH=/data/medvault.db
MEDVAULT_VAULT_DIR=/data/encrypted_labs
MEDVAULT_STEGO_DIR=/data/stego_scans
MEDVAULT_BIOMETRIC_DIR=/data/biometrics

MEDVAULT_MASTER_AES256_KEY_HEX=$(openssl rand -hex 32)
MEDVAULT_MASTER_ROOT_SECRET_HEX=$(openssl rand -hex 32)
MEDVAULT_STEGO_HMAC_KEY_HEX=$(openssl rand -hex 32)
MEDVAULT_SESSION_SECRET_HEX=$(openssl rand -hex 32)

MEDVAULT_VIGENERE_KEY=MEDVAULT-CLASSICAL-KEY-2026
MEDVAULT_TRANSPOSITION_KEY=KLINIK

MEDVAULT_VALIDATOR_PRIVKEY_HEX=$VALIDATOR_PRIV
MEDVAULT_VALIDATOR_PUBKEY_HEX=$VALIDATOR_PUB

MEDVAULT_DHASH_MAX_DISTANCE=14

MEDVAULT_WEBAUTHN_RP_DISPLAY_NAME=MedVault Go
MEDVAULT_WEBAUTHN_RPID=$RPID
MEDVAULT_WEBAUTHN_ORIGINS=$ORIGIN

MEDVAULT_SESSION_TTL_MINUTES=480
MEDVAULT_DEV_WEB_DIR=
EOF

chmod 600 "$ENV_FILE"

echo "wrote $ENV_FILE"
echo "WebAuthn RPID: $RPID"
echo "WebAuthn origin: $ORIGIN"
echo "validator public key: $VALIDATOR_PUB"
